const { chromium } = require('playwright');
const BASE='http://127.0.0.1:8020';
const kind=process.argv[2]||'d';
const vp= kind==='d' ? {width:1440,height:900} : {width:390,height:844};
const dpr= kind==='d' ? 1 : 2;
const email=process.argv[3]||`demo.${kind}.${Date.now()}@rejcc-demo.ci`;
(async()=>{
 const b=await chromium.launch({executablePath:'/opt/pw-browsers/chromium',args:['--no-sandbox']});
 const ctx=await b.newContext({viewport:vp,deviceScaleFactor:dpr,reducedMotion:'reduce'});
 await ctx.addInitScript(()=>{try{sessionStorage.setItem('rejcc_intro_seen','1')}catch(e){}});
 const p=await ctx.newPage(); const errs=[]; p.on('pageerror',e=>errs.push(e.message));
 let n=0; const shot=async(name)=>{await p.evaluate(()=>window.scrollTo(0,0)); await p.waitForTimeout(450); const f=`shots/${kind}_adh_${String(++n).padStart(2,'0')}_${name}`; await p.screenshot({path:f+'.jpg',type:'jpeg',quality:90}); await p.screenshot({path:f+'_full.jpg',type:'jpeg',quality:88,fullPage:true});};
 const wc=(sel)=>p.locator(sel);
 const chip=async(field,i=0)=>{ await wc(`[wire\\:click^="toggle('${field}'"]`).nth(i).click(); await p.waitForTimeout(250); };
 const sel1=async(field,i=0)=>{ await wc(`[wire\\:click^="select('${field}'"]`).nth(i).click(); await p.waitForTimeout(250); };
 const pick=async(id,idx=1)=>{ const o=await p.locator(`#${id} option`).nth(idx).getAttribute('value'); await p.selectOption(`#${id}`, o); await p.waitForTimeout(300); };
 const next=async()=>{ await p.locator('button[wire\\:click="next"]').click(); await p.waitForLoadState('networkidle'); await p.waitForTimeout(500); };
 await p.goto(BASE+'/adhesion',{waitUntil:'networkidle'});
 await shot('etape1_vide');
 await p.fill('#ma-nom-complet','Jean-Marc Kouadio'); await sel1('sexe',0); await pick('ma-age',2);
 await p.fill('#ma-whatsapp','+225 07 08 09 10 11'); await p.fill('#ma-email',email); await p.fill('#ma-ville','Abidjan');
 await p.fill('#ma-password',process.env.DEMO_PASSWORD); await p.fill('#ma-password-confirmation',process.env.DEMO_PASSWORD);
 await shot('etape1_rempli'); await next();
 await shot('etape2_vide'); await pick('ma-diocese',1); await p.waitForTimeout(600); await pick('ma-paroisse',1); await shot('etape2_rempli'); await next();
 await shot('etape3_vide'); await chip('statut_actuel',2); await pick('ma-etudes',4); await shot('etape3_rempli'); await next();
 await shot('etape4_vide'); await p.fill('#ma-domaines-formation','Gestion des entreprises'); await chip('competences',0); await chip('competences',3);
 await p.fill('#ma-competences-desc','Design graphique et gestion de projets digitaux.'); await shot('etape4_rempli'); await next();
 await shot('etape5_vide'); await sel1('a_activite',0); await p.waitForTimeout(400);
 await p.fill('#ma-nom-activite','Atelier Kouadio Design'); await chip('secteurs_activite',1); await pick('ma-anciennete',1); await shot('etape5_rempli_oui'); await next();
 await shot('etape6'); await next();   // le chemin qui plantait
 const crashed = await p.locator('text=SERVER ERROR').count();
 console.log('apres etape 6 -> crash 500 ?', crashed>0);
 await shot('etape7_vide'); await chip('attentes',0); await chip('attentes',2); await chip('formations_interet',1); await sel1('defi_principal',0); await pick('ma-revenu',2);
 await shot('etape7_rempli'); await next();
 await shot('etape8_recap');
 await next(); await p.waitForTimeout(1500); await shot('confirmation');
 console.log('confirmation ?', await p.locator('text=Merci').count()>0, 'email', email, 'errors', errs);
 require('fs').writeFileSync(`email_${kind}.txt`, email);
 await b.close();
})().catch(e=>{console.error('FATAL',e.message);process.exit(1)});
